    determinant = determinant3(matrix)
    check(rows, "internal", "characteristic coefficients independent", [trace, second, determinant] == [Fraction(2, 5), Fraction(223, 5000), Fraction(3, 3125)], [trace, second, determinant], [Fraction(2, 5), Fraction(223, 5000), Fraction(3, 3125)])
    internal_lower = Fraction(2811617233511, 10**14)
    internal_upper = Fraction(2811617233512, 10**14)
    pivots_lower = shifted_ldl_pivots(matrix, internal_lower)
