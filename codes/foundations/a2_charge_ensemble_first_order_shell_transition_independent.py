    atan239 = arctan_interval(Fraction(1, 239), 7)
    pi_lower = 16 * atan5[0] - 4 * atan239[1]
    pi_upper = 16 * atan5[1] - 4 * atan239[0]
    check(rows, "lattice", "rational Machin enclosure", Fraction(3) < pi_lower < pi_upper < Fraction(4), [pi_lower, pi_upper], "3<lower<upper<4")
    alpha_lower = pi_lower * pi_lower / 64
    alpha_upper = pi_upper * pi_upper / 64
    y_value, z_value, r_value = frac(params["Y"]), frac(params["Z"]), frac(params["r"])
    center = -z_value / (2 * y_value)
    ratio_lower, ratio_upper = center / alpha_upper, center / alpha_lower
    check(rows, "lattice", "unique radial shell m=3", Fraction(5, 2) < ratio_lower < ratio_upper < Fraction(7, 2), [ratio_lower, ratio_upper], "between 5/2 and 7/2")
    vectors = [(i, j, k) for i in range(-2, 3) for j in range(-2, 3) for k in range(-2, 3) if i * i + j * j + k * k == 3]
    check(rows, "lattice", "eight shell vectors", len(vectors) == 8, vectors, 8)
