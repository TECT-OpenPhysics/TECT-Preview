def frac(value: Any) -> Fraction:
    return Fraction(str(value))


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def encode(value: Any) -> Any:
    if isinstance(value, Fraction):
        return str(value)
    if isinstance(value, dict):
        return {str(key): encode(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [encode(item) for item in value]
    return value


def atomic_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(encode(payload), stream, indent=2, sort_keys=True, ensure_ascii=True)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def determinant3(matrix: list[list[Fraction]]) -> Fraction:
    a = matrix
    return (
        a[0][0] * (a[1][1] * a[2][2] - a[1][2] * a[2][1])
        - a[0][1] * (a[1][0] * a[2][2] - a[1][2] * a[2][0])
        + a[0][2] * (a[1][0] * a[2][1] - a[1][1] * a[2][0])
    )


def shifted_ldl_pivots(matrix: list[list[Fraction]], shift: Fraction) -> list[Fraction]:
    shifted = [[matrix[i][j] - (shift if i == j else 0) for j in range(3)] for i in range(3)]
    delta1 = shifted[0][0]
    delta2 = shifted[0][0] * shifted[1][1] - shifted[0][1] * shifted[1][0]
    delta3 = determinant3(shifted)
    return [delta1, delta2 / delta1, delta3 / delta2]


def arctan_interval(x: Fraction, terms: int) -> tuple[Fraction, Fraction]:
    partial = sum(((-1) ** j * x ** (2 * j + 1) / (2 * j + 1) for j in range(terms)), Fraction(0))
    remainder = x ** (2 * terms + 1) / (2 * terms + 1)
    return (partial, partial + remainder) if terms % 2 == 0 else (partial - remainder, partial)


def check(rows: list[dict[str, Any]], group: str, name: str, condition: bool, actual: Any, expected: Any) -> None:
    rows.append({"group": group, "name": name, "status": "PASS" if condition else "FAIL", "actual": encode(actual), "expected": encode(expected)})


