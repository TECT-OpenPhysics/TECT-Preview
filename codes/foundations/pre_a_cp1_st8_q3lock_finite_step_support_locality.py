#!/usr/bin/env python3
"""Exact finite-step support audit for the Q3 onsite-plus-all-bond split.

The calculation is algebraic.  It records the closed-neighbourhood support
map generated by the all-bond configuration kick and keeps the existence of
the site-local onsite flow as an explicit hypothesis.  It does not estimate
operator norms or take the Trotter-count limit.
"""

from __future__ import annotations

