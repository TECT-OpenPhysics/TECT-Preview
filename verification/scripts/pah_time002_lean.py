#!/usr/bin/env python3
"""TIME-002 fresh pinned Lean replay, five partial path/clock/moment bridges."""
import argparse
import hashlib
import json
from pathlib import Path
import pah_v2_gd001_lean as harness

ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'verification/lean/Tect/PahClockPathFreezing.lean'
OUT=ROOT/'claims/C6-SPACETIME-SIGNATURE/runs/2026-10-14-pah-time002/lean.json'
HARNESS_HASH='76035cd98d8bba5907776c509b7b0c9afc72e68c5c84bc588611832c6dfecf32'


def main():
    if not __debug__:
        raise RuntimeError('Assertions must be enabled')
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--lean-cache',type=Path,default=ROOT/'verification/lean/.lake/packages')
    p.add_argument('--elan-home',type=Path,default=Path.home()/'.elan')
    p.add_argument('--write',action='store_true')
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    assert hashlib.sha256(Path(harness.__file__).read_bytes()).hexdigest()==HARNESS_HASH
    harness.SOURCE=SOURCE
    result=harness.run(a.lean_cache,a.elan_home)
    result.update(schema='tect/pah-time002-lean/1.0',status='PASS_PARAMETERIZED_PATH_CLOCK_BRIDGES',
        script_version='1.0.0',script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        compiler_harness_sha256=HARNESS_HASH,
        equivalent_lake_command='cd verification/lean; lake env lean Tect/PahClockPathFreezing.lean',
        scope='Five supplied-moment, path envelope, inverse horizon, integral monotonicity and limit-domination bridges.',
        not_encoded='Source finite path law, labelled Poisson construction/moments, jump/rate cap, clock integral inverse and K_r divergence remain analytic. Supremum measurability/integrability are justified in the note, not generated by Lean.',
        non_claims='No full-model Lean encoding, physical clock, common-limit process, Pre-A, QFT, gravity or external-person certification.')
    if a.write:
        assert not OUT.exists(),'Issued run immutable; use --check'
        OUT.parent.mkdir(parents=True,exist_ok=True)
        OUT.write_text(json.dumps(result,sort_keys=True,indent=2)+'\n',encoding='utf-8',newline='\n')
    else:
        old=json.loads(OUT.read_text(encoding='utf-8'))
        assert {k:v for k,v in old.items() if k!='environment'}=={k:v for k,v in result.items() if k!='environment'}
    print('TIME-002 LEAN: PASS',len(result['declarations']),'parameterized declarations')


if __name__=='__main__':
    main()
